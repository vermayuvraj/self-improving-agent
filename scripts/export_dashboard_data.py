"""Export completed benchmark runs to dashboard/runs.js.

Reads runs/*/manifest.json (written by sia.runner), keeps completed runs, and
emits the array the dashboard's Results section renders. Run after any
experiment: `uv run python scripts/export_dashboard_data.py`.
"""

from __future__ import annotations

import json
from pathlib import Path

from sia.bench import wilson_ci

ROOT = Path(__file__).resolve().parent.parent
RUNS_DIR = ROOT / "runs"
OUT = ROOT / "dashboard" / "runs.js"


def collect() -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    for manifest_path in sorted(RUNS_DIR.glob("*/manifest.json")):
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        if manifest.get("outcome") != "completed":
            continue
        totals = manifest.get("totals", {})
        config = manifest.get("config", {})
        if config.get("limit") is not None:
            continue  # smoke/subset runs are pipeline checks, never results
        pass1 = totals.get("pass@1")
        tasks = totals.get("tasks")
        if pass1 is None or not tasks:
            continue
        row: dict[str, object] = {
            "run_id": manifest["run_id"],
            "date": manifest.get("created_at", "")[:10],
            "bench": config.get("bench"),
            "model": manifest.get("model"),
            "pass1": round(pass1, 4),
            "tasks": tasks,
            "samples": config.get("samples", 1),
        }
        if config.get("samples", 1) == 1:
            lo, hi = wilson_ci(round(pass1 * tasks), tasks)
            row["ci"] = [round(lo, 4), round(hi, 4)]
        rows.append(row)
    return rows


def main() -> None:
    rows = collect()
    OUT.write_text(
        "// Generated by scripts/export_dashboard_data.py — do not edit by hand.\n"
        f"window.SIA_RUNS = {json.dumps(rows, indent=2)};\n",
        encoding="utf-8",
    )
    print(f"wrote {len(rows)} run(s) to {OUT}")


if __name__ == "__main__":
    main()
